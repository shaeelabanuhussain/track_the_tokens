'use strict';
// PDF -> Markdown. Claude reads a PDF as page images plus text (~1.5-3k tokens
// per page); the same content as Markdown is usually a fraction of that.
// Tries the best converter available, falling back to a built-in extractor so
// it works with zero installs.

const fs = require('fs');
const path = require('path');
const zlib = require('zlib');
const { execFileSync } = require('child_process');

const MARKER = '<!-- generated by tokenlens pdf2md';
const IMAGE_TOKENS_PER_PAGE = 1600;

function has(cmd) {
  try {
    execFileSync(process.platform === 'win32' ? 'where' : 'which', [cmd], { stdio: 'ignore' });
    return true;
  } catch {
    return false;
  }
}

function run(cmd, args) {
  return execFileSync(cmd, args, { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024, stdio: ['ignore', 'pipe', 'ignore'], timeout: 60000 });
}

function viaMarkitdown(file) {
  if (!has('markitdown')) return null;
  return run('markitdown', [file]);
}

function viaPdftotext(file) {
  if (!has('pdftotext')) return null;
  return textToMarkdown(run('pdftotext', ['-layout', file, '-']));
}

function viaPython(file) {
  const py = has('python3') ? 'python3' : has('python') ? 'python' : null;
  if (!py) return null;
  const code = [
    'import sys',
    'try:',
    '    import pdfplumber',
    '    with pdfplumber.open(sys.argv[1]) as pdf:',
    '        print("\\f".join((p.extract_text() or "") for p in pdf.pages))',
    'except ImportError:',
    '    from pypdf import PdfReader',
    '    print("\\f".join((p.extract_text() or "") for p in PdfReader(sys.argv[1]).pages))',
  ].join('\n');
  try {
    return textToMarkdown(run(py, ['-I', '-c', code, file]));
  } catch {
    return null;
  }
}

// Minimal extractor: inflate content streams, pull strings from Tj/TJ operators.
// Good enough for text-based PDFs with standard fonts; scanned PDFs need OCR.
function viaBuiltin(file) {
  const buf = fs.readFileSync(file);
  const bin = buf.toString('latin1');
  const pages = [];
  const re = /stream\r?\n/g;
  let m;
  while ((m = re.exec(bin))) {
    const start = m.index + m[0].length;
    const end = bin.indexOf('endstream', start);
    if (end < 0) break;
    const dict = bin.slice(Math.max(0, m.index - 400), m.index);
    let data = buf.subarray(start, end);
    if (/\/FlateDecode/.test(dict.slice(dict.lastIndexOf('<<')))) {
      try {
        data = zlib.inflateSync(data);
      } catch {
        try {
          data = zlib.inflateRawSync(data.subarray(2));
        } catch {
          continue;
        }
      }
    }
    const s = data.toString('latin1');
    if (!/BT[\s\S]*?ET/.test(s)) continue;
    const lines = [];
    for (const block of s.match(/BT[\s\S]*?ET/g)) {
      let line = '';
      const ops = block.match(/\((?:\\.|[^\\)])*\)\s*(?:Tj|'|")|\[(?:[^\]]*)\]\s*TJ|T\*|-?\d+(?:\.\d+)?\s+-?\d+(?:\.\d+)?\s+T[dD]/g) || [];
      for (const op of ops) {
        if (/T[dD*]$/.test(op)) {
          if (line.trim()) lines.push(line);
          line = '';
          continue;
        }
        const strs = op.match(/\((?:\\.|[^\\)])*\)/g) || [];
        for (const str of strs) line += unescapePdf(str.slice(1, -1));
      }
      if (line.trim()) lines.push(line);
    }
    if (lines.length) pages.push(lines.join('\n'));
  }
  const text = pages.join('\n\n');
  const printable = text.replace(/[^\x20-\x7e\n]/g, '').length;
  if (!text.trim() || printable / text.length < 0.85) return null;
  return textToMarkdown(text);
}

function unescapePdf(s) {
  return s
    .replace(/\\([nrtbf()\\])/g, (_, c) => ({ n: '\n', r: '', t: '\t', b: '', f: '', '(': '(', ')': ')', '\\': '\\' })[c])
    .replace(/\\(\d{1,3})/g, (_, o) => String.fromCharCode(parseInt(o, 8)));
}

// Plain text -> light Markdown: page breaks become rules, all-caps lines become
// headings, bullet glyphs become list items, runs of spaces collapse.
function textToMarkdown(text) {
  const out = [];
  for (const page of text.split('\f')) {
    const lines = page.split('\n').map((l) => l.replace(/\s+$/, ''));
    for (let raw of lines) {
      let l = raw.replace(/ {3,}/g, '  ').trim();
      if (!l) {
        if (out.length && out[out.length - 1] !== '') out.push('');
        continue;
      }
      if (/^[•●▪◦‣∙·\-*]\s+/.test(l)) l = '- ' + l.replace(/^[•●▪◦‣∙·\-*]\s+/, '');
      else if (l.length <= 70 && /^[A-Z0-9][A-Z0-9 &:,'’\-–—/()]+$/.test(l) && /[A-Z]{3}/.test(l)) l = '## ' + titleCase(l);
      out.push(l);
    }
    out.push('', '---', '');
  }
  while (out.length && (out[out.length - 1] === '' || out[out.length - 1] === '---')) out.pop();
  return out.join('\n').replace(/\n{3,}/g, '\n\n') + '\n';
}

function titleCase(s) {
  return s.toLowerCase().replace(/(^|\s)(\S)/g, (_, a, b) => a + b.toUpperCase());
}

function countPages(file) {
  const bin = fs.readFileSync(file).toString('latin1');
  const n = (bin.match(/\/Type\s*\/Page[^s]/g) || []).length;
  return n || 1;
}

function targetPath(pdf) {
  const md = pdf.replace(/\.pdf$/i, '.md');
  if (!fs.existsSync(md)) return md;
  const head = fs.readFileSync(md, 'utf8').slice(0, 200);
  return head.startsWith(MARKER) ? md : pdf + '.md';
}

// Returns { mdPath, pages, pdfTokens, mdTokens, savedTokens, savedPct, engine, cached }
function convert(pdf, { force = false, engine: only = null } = {}) {
  pdf = path.resolve(pdf);
  const mdPath = targetPath(pdf);
  const pages = countPages(pdf);
  if (!force && fs.existsSync(mdPath) && fs.statSync(mdPath).mtimeMs >= fs.statSync(pdf).mtimeMs) {
    const md = fs.readFileSync(mdPath, 'utf8');
    return stats(pdf, mdPath, md, pages, 'cache', true);
  }
  let md = null;
  let engine = null;
  for (const [name, fn] of [['pdftotext', viaPdftotext], ['markitdown', viaMarkitdown], ['python', viaPython], ['builtin', viaBuiltin]]) {
    if (only && name !== only) continue;
    try {
      md = fn(pdf);
    } catch {
      md = null;
    }
    if (md && md.trim().length > 20) {
      md = md.replace(/\t+/g, ' ').replace(/[ \t]+$/gm, '');
      engine = name;
      break;
    }
  }
  if (!md) {
    const err = new Error('Could not extract text (scanned/image PDF?). Install markitdown (pip install markitdown) or poppler-utils for better results.');
    err.code = 'NO_TEXT';
    throw err;
  }
  const header = `${MARKER} from ${path.basename(pdf)} via ${engine}; ${pages} page(s) -->\n\n`;
  fs.writeFileSync(mdPath, header + md);
  return stats(pdf, mdPath, header + md, pages, engine, false);
}

function stats(pdf, mdPath, md, pages, engine, cached) {
  const mdTokens = Math.round(md.length / 4);
  const pdfTokens = mdTokens + pages * IMAGE_TOKENS_PER_PAGE;
  const savedTokens = Math.max(0, pdfTokens - mdTokens);
  return { pdf, mdPath, pages, pdfTokens, mdTokens, savedTokens, savedPct: pdfTokens ? savedTokens / pdfTokens : 0, engine, cached };
}

module.exports = { convert, textToMarkdown };
